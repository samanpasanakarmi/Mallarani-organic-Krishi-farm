document.addEventListener("DOMContentLoaded", function () {
  const savedLanguage = localStorage.getItem("farmLanguage");

  if (savedLanguage === "np" || savedLanguage === "en") {
    currentLanguage = savedLanguage;
  }

  const contactForm = document.getElementById("contactForm");
  const menuToggle = document.getElementById("menuToggle");
  const navMenu = document.getElementById("navMenu");
  const availableGrid = document.getElementById("availableGrid");
  const priceGrid = document.getElementById("priceGrid");
  const categoryFilters = document.getElementById("categoryFilters");
  const updatesGrid = document.getElementById("updatesGrid");
  const englishButton = document.getElementById("englishButton");
  const nepaliButton = document.getElementById("nepaliButton");

  function getText(enValue, npValue) {
    if (currentLanguage === "np" && npValue) {
      return npValue;
    }

    return enValue;
  }

  function applyFarmInfo() {
    if (typeof farmInfo === "undefined") {
      return;
    }

    document.querySelectorAll("[data-farm-name]").forEach(function (element) {
      element.textContent = getText(farmInfo.name, farmInfo.nameNp);
    });

    document.querySelectorAll("[data-farm-slogan]").forEach(function (element) {
      element.textContent = getText(farmInfo.slogan, farmInfo.sloganNp);
    });

    document.querySelectorAll("[data-farm-phone]").forEach(function (element) {
      element.textContent = farmInfo.phone;
    });

    document.querySelectorAll("[data-farm-email]").forEach(function (element) {
      element.textContent = farmInfo.email;
    });

    document.querySelectorAll("[data-farm-owner]").forEach(function (element) {
      element.textContent = getText(farmInfo.owner, farmInfo.ownerNp);
    });

    document.querySelectorAll("[data-farm-hours]").forEach(function (element) {
      element.textContent = getText(farmInfo.visitingHours, farmInfo.visitingHoursNp);
    });

    document.querySelectorAll("[data-farm-location]").forEach(function (element) {
      element.textContent = getText(farmInfo.locationName, farmInfo.locationNameNp);
    });

    document.querySelectorAll("[data-call-link]").forEach(function (button) {
      button.href = `tel:${farmInfo.phone}`;
    });

    document.querySelectorAll("[data-whatsapp-link]").forEach(function (button) {
      button.href = `https://wa.me/${farmInfo.whatsappNumber}`;
    });

    document.querySelectorAll("[data-map-link]").forEach(function (button) {
      button.href = farmInfo.mapLink;
    });
  }

  function applyStaticTranslations() {
    document.documentElement.lang = currentLanguage === "np" ? "ne" : "en";

    document.querySelectorAll("[data-i18n]").forEach(function (element) {
      const key = element.getAttribute("data-i18n");

      if (translations[currentLanguage][key]) {
        element.textContent = translations[currentLanguage][key];
      }
    });

    document.querySelectorAll("[data-placeholder-key]").forEach(function (element) {
      const key = element.getAttribute("data-placeholder-key");

      if (translations[currentLanguage][key]) {
        element.placeholder = translations[currentLanguage][key];
      }
    });

    if (englishButton && nepaliButton) {
      englishButton.classList.toggle("active", currentLanguage === "en");
      nepaliButton.classList.toggle("active", currentLanguage === "np");
    }
  }

  function renderCategoryFilters() {
    if (!categoryFilters || typeof farmProducts === "undefined") {
      return;
    }

    const categories = [
      {
        en: "All",
        np: translations.np.allCategory
      }
    ];

    farmProducts.forEach(function (product) {
      const categoryEn = product.category || "Other";
      const categoryNp = product.categoryNp || categoryEn;

      const alreadyExists = categories.some(function (category) {
        return category.en === categoryEn;
      });

      if (!alreadyExists) {
        categories.push({
          en: categoryEn,
          np: categoryNp
        });
      }
    });

    categoryFilters.innerHTML = categories.map(function (category, index) {
      const activeClass = index === 0 ? "active" : "";
      const label = currentLanguage === "np" ? category.np : category.en;

      return `
        <button 
          class="category-filter-button ${activeClass}" 
          data-category="${category.en}"
        >
          ${label}
        </button>
      `;
    }).join("");

    document.querySelectorAll(".category-filter-button").forEach(function (button) {
      button.addEventListener("click", function () {
        document.querySelectorAll(".category-filter-button").forEach(function (btn) {
          btn.classList.remove("active");
        });

        button.classList.add("active");

        const selectedCategory = button.getAttribute("data-category");

        renderAvailableProducts(selectedCategory);
      });
    });
  }

  function renderAvailableProducts(selectedCategory) {
    if (!availableGrid || typeof farmProducts === "undefined") {
      return;
    }

    const filteredProducts = selectedCategory === "All"
      ? farmProducts
      : farmProducts.filter(function (product) {
          return product.category === selectedCategory;
        });

    if (filteredProducts.length === 0) {
      availableGrid.innerHTML = `<p>${translations[currentLanguage].noCategoryProducts}</p>`;
      return;
    }

    availableGrid.innerHTML = filteredProducts.map(function (product) {
      const productImage = product.image ? product.image : "images/vegetables.jpg";
      const productName = getText(product.name, product.nameNp);
      const productPrice = getText(product.price, product.priceNp);
      const productStatus = getText(product.status, product.statusNp);
      const productCategory = getText(product.category || "Farm Product", product.categoryNp);
      const productDescription = getText(product.description, product.descriptionNp);

      return `
        <div class="available-card">
          <img class="available-image" src="${productImage}" alt="${productName}">
          <div class="available-card-content">
            <span class="available-tag">${productStatus}</span>
            <span class="product-category">${productCategory}</span>
            <h3>${productName}</h3>
            <p>${productDescription}</p>
            <p class="available-price">${productPrice}</p>
            <button onclick="orderProduct('${productName}')">${translations[currentLanguage].orderWhatsapp}</button>
          </div>
        </div>
      `;
    }).join("");

    setupRevealAnimation();
  }

  function renderPriceList() {
    if (!priceGrid || typeof farmProducts === "undefined") {
      return;
    }

    priceGrid.innerHTML = farmProducts.map(function (product) {
      const productName = getText(product.name, product.nameNp);
      const productPrice = getText(product.price, product.priceNp);
      const productCategory = getText(product.category || "Farm Product", product.categoryNp);

      return `
        <div class="price-card">
          <h3>${productName}</h3>
          <p class="product-category">${productCategory}</p>
          <p class="price">${productPrice}</p>
          <button onclick="orderProduct('${productName}')">${translations[currentLanguage].orderNow}</button>
        </div>
      `;
    }).join("");
  }

  function renderFarmUpdates() {
    if (!updatesGrid || typeof farmUpdates === "undefined") {
      return;
    }

    if (farmUpdates.length === 0) {
      updatesGrid.innerHTML = `<p>${translations[currentLanguage].noUpdates}</p>`;
      return;
    }

    updatesGrid.innerHTML = farmUpdates.map(function (update) {
      const title = getText(update.title, update.titleNp);
      const description = getText(update.description, update.descriptionNp);
      const tag = getText(update.tag, update.tagNp);

      return `
        <div class="update-card">
          <span class="update-tag">${tag}</span>
          <h3>${title}</h3>
          <p class="update-date">${update.date}</p>
          <p>${description}</p>
        </div>
      `;
    }).join("");
  }

  function applyLanguage() {
    localStorage.setItem("farmLanguage", currentLanguage);

    applyStaticTranslations();
    applyFarmInfo();
    renderCategoryFilters();
    renderAvailableProducts("All");
    renderPriceList();
    renderFarmUpdates();
    setupRevealAnimation();
  }

  if (englishButton) {
    englishButton.addEventListener("click", function () {
      currentLanguage = "en";
      applyLanguage();
    });
  }

  if (nepaliButton) {
    nepaliButton.addEventListener("click", function () {
      currentLanguage = "np";
      applyLanguage();
    });
  }

  applyLanguage();

  if (menuToggle && navMenu) {
    menuToggle.addEventListener("click", function () {
      navMenu.classList.toggle("active");
    });
  }

  document.querySelectorAll(".nav-menu a").forEach(function (link) {
    link.addEventListener("click", function () {
      if (navMenu) {
        navMenu.classList.remove("active");
      }
    });
  });

  if (contactForm) {
    contactForm.addEventListener("submit", function (event) {
      event.preventDefault();

      const name = document.getElementById("name").value;
      const phone = document.getElementById("phone").value;
      const message = document.getElementById("message").value;

      const farmName = typeof farmInfo !== "undefined"
        ? getText(farmInfo.name, farmInfo.nameNp)
        : "Mallarani Organic Krisha Farm";

      const farmPhoneNumber = typeof farmInfo !== "undefined"
        ? farmInfo.whatsappNumber
        : "9779844959890";

      const whatsappMessage =
        currentLanguage === "np"
          ? `नमस्ते ${farmName},%0A%0Aनाम: ${name}%0Aफोन: ${phone}%0Aसन्देश: ${message}`
          : `Hello ${farmName},%0A%0AName: ${name}%0APhone: ${phone}%0AMessage: ${message}`;

      const whatsappURL =
        `https://wa.me/${farmPhoneNumber}?text=${whatsappMessage}`;

      window.open(whatsappURL, "_blank");
    });
  }

  const galleryImages = document.querySelectorAll(".gallery-grid img");
  const lightbox = document.getElementById("lightbox");
  const lightboxImage = document.getElementById("lightboxImage");
  const closeLightbox = document.getElementById("closeLightbox");

  galleryImages.forEach(function (image) {
    image.addEventListener("click", function () {
      if (lightbox && lightboxImage) {
        lightbox.style.display = "flex";
        lightboxImage.src = image.src;
      }
    });
  });

  if (closeLightbox && lightbox) {
    closeLightbox.addEventListener("click", function () {
      lightbox.style.display = "none";
    });
  }

  if (lightbox) {
    lightbox.addEventListener("click", function (event) {
      if (event.target === lightbox) {
        lightbox.style.display = "none";
      }
    });
  }

  function setupRevealAnimation() {
    const revealElements = document.querySelectorAll(
      ".section, .highlight-card, .why-card, .practice-card, .available-card, .delivery-card, .product-card, .price-card, .update-card, .testimonial-card, .faq-item"
    );

    revealElements.forEach(function (element) {
      element.classList.add("reveal");
    });

    revealOnScroll();
  }

  function revealOnScroll() {
    const revealElements = document.querySelectorAll(".reveal");
    const windowHeight = window.innerHeight;

    revealElements.forEach(function (element) {
      const elementTop = element.getBoundingClientRect().top;

      if (elementTop < windowHeight - 80) {
        element.classList.add("active");
      }
    });
  }

  window.addEventListener("scroll", revealOnScroll);

  const backToTop = document.getElementById("backToTop");

  if (backToTop) {
    window.addEventListener("scroll", function () {
      if (window.scrollY > 400) {
        backToTop.classList.add("show");
      } else {
        backToTop.classList.remove("show");
      }
    });

    backToTop.addEventListener("click", function () {
      window.scrollTo({
        top: 0,
        behavior: "smooth"
      });
    });
  }
});

function orderProduct(productName) {
  const farmName = typeof farmInfo !== "undefined"
    ? (currentLanguage === "np" && farmInfo.nameNp ? farmInfo.nameNp : farmInfo.name)
    : "Mallarani Organic Krisha Farm";

  const farmPhoneNumber = typeof farmInfo !== "undefined"
    ? farmInfo.whatsappNumber
    : "9779844959890";

  const message =
    currentLanguage === "np"
      ? `नमस्ते ${farmName},%0A%0Aम यो उत्पादन अर्डर गर्न चाहन्छु: ${productName}%0Aकृपया मूल्य र उपलब्धता जानकारी दिनुहोस्।`
      : `Hello ${farmName},%0A%0AI want to order: ${productName}%0APlease share price and availability.`;

  const whatsappURL =
    `https://wa.me/${farmPhoneNumber}?text=${message}`;

  window.open(whatsappURL, "_blank");
}
// V2: keep the mobile navigation state accessible.
(() => {
  const toggle = document.getElementById('menuToggle');
  const menu = document.getElementById('navMenu');
  if (!toggle || !menu) return;
  const sync = () => toggle.setAttribute('aria-expanded', menu.classList.contains('active') ? 'true' : 'false');
  toggle.addEventListener('click', () => setTimeout(sync, 0));
  menu.querySelectorAll('a').forEach(link => link.addEventListener('click', () => setTimeout(sync, 0)));
  sync();
})();
